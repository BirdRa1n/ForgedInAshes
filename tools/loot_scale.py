"""Generate <set> patches that scale the loot count of items in loot.xml.

Each loot <item name=X count="a,b"> (or count="n") inside a lootgroup/lootcontainer gets
count = (max(1, ceil(a*f)), max(1, ceil(b*f))). Entries whose count cannot go lower
(already 1) are listed as comments, not patched. factor 0 -> prints <remove> instead.

Usage:
  python tools/loot_scale.py <factor> <item> [<item> ...]
  python tools/loot_scale.py 0.5 resourceMechanicalParts resourceSpring
"""
import collections
import math
import sys

import fe_common as fe


def scale(count: str, f: float) -> str:
    parts = [int(x) for x in count.split(",")]
    new = [max(1, math.ceil(p * f)) for p in parts]
    return ",".join(str(n) for n in new)


def main() -> int:
    if len(sys.argv) < 3:
        print(__doc__)
        return 2
    f = float(sys.argv[1])
    items = sys.argv[2:]
    root = fe.load_vanilla("loot.xml").getroot()
    print(f"<!-- generated by tools/loot_scale.py {sys.argv[1]} {' '.join(items)} -->")
    for item in items:
        # Group entries by parent so repeated entries in one parent use a positional predicate.
        per_parent = collections.defaultdict(list)
        for it in root.iter("item"):
            if it.get("name") == item:
                p = it.getparent()
                per_parent[(p.tag, p.get("name"))].append(it)
        for (tag, pname), entries in per_parent.items():
            for idx, it in enumerate(entries, 1):
                pos = f"[{idx}]" if len(entries) > 1 else ""
                base = f"/lootcontainers/{tag}[@name='{pname}']/item[@name='{item}']{pos}"
                if f == 0:
                    print(f'\t<remove xpath="{base}"/>')
                    continue
                count = it.get("count") or "1"
                new = scale(count, f)
                if new == count:
                    print(f"\t<!-- {tag} {pname}: {item} count={count} already minimal, unchanged -->")
                else:
                    print(f'\t<set xpath="{base}/@count">{new}</set>  <!-- was {count} -->')
    return 0


if __name__ == "__main__":
    sys.exit(main())
