def fmt(v):
    return ("%g" % v)


def proc_xml(p):
    a = [f'id="{p["id"]}"', f'kind="{p["kind"]}"', f'machine="{p["machine"]}"']
    if p["inputs"]:
        a.append('input="%s"' % ",".join(n for n, _ in p["inputs"]))
        a.append('count="%s"' % ",".join(str(c) for _, c in p["inputs"]))
    if p["mold"]:
        a.append(f'mold="{p["mold"]}"')
    if p["fin"]:
        a.append('fluid_in="%s"' % ",".join(n for n, _ in p["fin"]))
        a.append('liters="%s"' % ",".join(fmt(c) for _, c in p["fin"]))
    if p["out"]:
        a.append(f'output="{p["out"]}" out_count="{p["n"]}"')
    if p["fout"]:
        a.append('fluid_out="%s"' % ",".join(n for n, _ in p["fout"]))
        a.append('out_liters="%s"' % ",".join(fmt(c) for _, c in p["fout"]))
    if p["extra"]:
        a.append(f'extra="{p["extra"]}" extra_count="{p["extra_n"]}"' + (f' chance="{p["chance"]}"' if p["chance"] < 1 else ""))
    a.append(f'time="{fmt(p["time"])}"')
    if p["torque"]:
        a.append(f'torque="{p["torque"]}"')
    if p["pressure"]:
        a.append(f'pressure="{fmt(p["pressure"])}"')
    if p["heat"]:
        a.append('heat="true"')
    if p.get("keep"):
        a.append('keep="%s"' % ",".join(p["keep"]))
    if p.get("boost"):
        a.append(f'boost="{p["boost"]}" boost_speed="{fmt(p["boost_speed"])}"')
    if p["text"]:
        a.append(f'text="{esc(p["text"])}"')
    return "\t<process " + " ".join(a) + "/>"


