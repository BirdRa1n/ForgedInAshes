# Industrial Cooker: every food recipe of the Kitchen (KEEP+COPY of the campfire), x4 at half the time per unit
def cooker_processes():
    t, _ = fe.patched("recipes.xml")
    seen = set()
    for r in t.getroot().iter("recipe"):
        if r.get("craft_area") not in ("feKitchen", "campfire"):
            continue
        name = r.get("name")
        if not (name.startswith("food") or name.startswith("drink")) or name in seen:
            continue
        seen.add(name)
        ins = [(i.get("name"), int(i.get("count", "1")) * 4) for i in r.iter("ingredient") if int(i.get("count", "1")) > 0]
        if not ins or len(ins) > 6:
            continue
        cnt = int(r.get("count", "1")) * 4
        tm = float(r.get("craft_time", "10") or 10) * 2
        proc("cook_" + name, "boil", "feCookerIndustrial", ins, name, cnt, tm, heat=True, text="Cozinha Industrial: lote de 4.")


