def write_localization():
    p = fe.MOD_CONFIG / "Localization.csv"
    with p.open(encoding="utf-8", newline="") as fh:
        reader = list(csv.reader(fh))
    header, body = reader[0], reader[1:]
    new = loc_rows()
    keys = {r[0] for r in new}
    body = [r for r in body if r and r[0] not in keys]
    ie, ib = header.index("english"), header.index("brazilian")
    for key, f, typ, en, pt in new:
        row = [""] * len(header)
        row[0], row[1], row[2], row[ie], row[ib] = key, f, typ, en, pt
        body.append(row)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(body)
    p.write_text(buf.getvalue(), encoding="utf-8")


def check():
    errors = []
    vanilla = {e.get("name") for f in ("items.xml", "blocks.xml") for e in fe.load_vanilla(f).getroot()}
    mod = set()
    for f in ("items.xml", "blocks.xml"):
        t, _ = fe.patched(f)
        mod |= {e.get("name") for e in t.getroot().iter("item")} | {e.get("name") for e in t.getroot().iter("block")}
    mine = {i[0] for i in I} | {b[0] for b in B} | {t[0] for t in TREE}
    known = vanilla | mod | mine
    icons = fe.game_dir() / "Data" / "ItemIcons"
    atlas = fe.MOD_DIR / "UIAtlases" / "ItemIconAtlas"
    for i in I:
        if not (icons / f"{i[3]}.png").exists() and not (atlas / f"{i[3]}.png").exists():
            errors.append(f"icon missing: {i[3]} ({i[0]})")
    for b in B:
        if not (atlas / f"{b[8]}.png").exists():
            errors.append(f"icon missing: {b[8]} ({b[0]})")
        errors += [f"unknown ingredient {n} in {b[0]}" for n, _ in b[10] if n not in known]
        if b[5] not in known:
            errors.append(f"unknown base {b[5]} in {b[0]}")
    for r in RECIPES:
        if r[0] not in known:
            errors.append(f"unknown recipe output {r[0]}")
        errors += [f"unknown ingredient {n} in recipe {r[0]}" for n, _ in r[4] if n not in known]
    fluids = {f[0] for f in FLUIDS} | {"water", "steam", "oil", "gasoline", "lubricant", "molten_brass", "molten_lead", "molten_iron", "molten_steel"}
    machines = {b[0] for b in B} | mod
    for p in P:
        for n, _ in p["inputs"]:
            if n not in known:
                errors.append(f"process {p['id']}: unknown input {n}")
        for n in [p["out"], p["extra"], p["mold"]]:
            if n and n not in known:
                errors.append(f"process {p['id']}: unknown item {n}")
        for f, _ in p["fin"] + p["fout"]:
            if f not in fluids:
                errors.append(f"process {p['id']}: unknown fluid {f}")
        if p["machine"] not in machines:
            errors.append(f"process {p['id']}: unknown machine {p['machine']}")
    recipes, _ = fe.patched("recipes.xml")
    have = {(r.get("name"), r.get("craft_area")) for r in recipes.getroot().iter("recipe")}
    for n, a, ings in APPEND:
        if (n, a) not in have:
            errors.append(f"append: recipe {n} @ {a} not found")
        errors += [f"append {n}: unknown {i}" for i, _ in ings if i not in known]
    return errors


def write_fallback():
    """D12-4: the shortcuts removed above, at 3x their cost, for VanillaShortcuts=expensive (Settings.cs)."""
    van = fe.load_vanilla("recipes.xml").getroot()
    out = ['<?xml version="1.0" encoding="UTF-8"?>',
           f"<!-- GENERATED by {TAG}: the game's shortcuts the chains replace, at 3x their cost. Used only with",
           '     Data/fe_settings.xml VanillaShortcuts="expensive". -->', "<recipes>"]
    for name, area in REMOVE_RECIPE:
        for r in van.iter("recipe"):
            if r.get("name") != name or "salvageScrap" in (r.get("tags") or "") or r.get("craft_area") in (None, ""):
                continue
            ings = [(i.get("name"), int(i.get("count", "1")) * 3) for i in r.iter("ingredient")
                    if not i.get("name", "").startswith("unit_") and int(i.get("count", "1")) > 0]
            if not ings:
                continue
            out.append(f'\t<recipe name="{name}" count="{r.get("count", "1")}" craft_area="{area}" craft_time="{r.get("craft_time", "10")}">')
            out += [f'\t\t<ingredient name="{i}" count="{c}"/>' for i, c in ings]
            out.append("\t</recipe>")
            break
    out.append("</recipes>")
    (fe.MOD_DIR / "Data" / "fe_fallback.xml").write_text("\n".join(out) + "\n", encoding="utf-8")
    st = fe.MOD_DIR / "Data" / "fe_settings.xml"
    if not st.exists():
        st.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- ForgedInAshes settings (Settings.cs).\n'
                      '     VanillaShortcuts: remove (default) = the shortcuts the chains replace are gone;\n'
                      '                       expensive = they come back at 3x their cost (Data/fe_fallback.xml). -->\n'
                      '<settings>\n\t<setting name="VanillaShortcuts" value="remove"/>\n</settings>\n', encoding="utf-8")


def mod_appends():
    t, _ = fe.patched("recipes.xml")
    for r in t.getroot().iter("recipe"):
        if r.get("craft_area") == "feModBench" and r.get("name", "").startswith("mod"):
            APPEND.append((r.get("name"), "feModBench", mod_parts(r.get("name"))))


def main():
    cooker_processes()
    mod_appends()
    # unique appends
    seen, uniq = set(), []
    for a in APPEND:
        if (a[0], a[1]) in seen:
            continue
        seen.add((a[0], a[1]))
        uniq.append(a)
    APPEND[:] = uniq
    errors = check()
    for e in errors:
        print("ERROR:", e)
    if errors:
        return 1
    if "--check" in sys.argv:
        print("check OK")
        return 0
    write_region(fe.MOD_CONFIG / "items.xml", '\t<append xpath="/items">\n' + "\n".join(item_xml(i) for i in I) + "\n\t</append>")
    write_region(fe.MOD_CONFIG / "blocks.xml", '\t<append xpath="/blocks">\n' + "\n".join(block_xml(b) for b in B) + "\n" + tree_xml() + "\n\t</append>")
    rec = [recipe_xml(b[0], b[11], "feAssembler", 20, b[10]) for b in B if b[10]]
    rec += [recipe_xml(*r) for r in RECIPES]
    # whole recipes replaced by the chain go first (a new recipe of the same name is appended after them)
    body = [f"\t<remove xpath=\"/recipes/recipe[@name='{n}'][@craft_area='{a}']\"/>" for n, a in REMOVE_RECIPE]
    body += ['\t<append xpath="/recipes">', "\n".join(rec), "\t</append>"]
    for n, a, ings in APPEND:
        ing = "\n".join(f'\t\t<ingredient name="{i}" count="{c}"/>' for i, c in ings)
        body.append(f"\t<append xpath=\"/recipes/recipe[@name='{n}'][@craft_area='{a}']\">\n{ing}\n\t</append>")
    for n, a, i in REMOVE_ING:
        body.append(f"\t<remove xpath=\"/recipes/recipe[@name='{n}'][@craft_area='{a}']/ingredient[@name='{i}']\"/>")
    write_region(fe.MOD_CONFIG / "recipes.xml", "\n".join(body))
    write_processes()
    write_fallback()
    write_localization()
    # same icon placement as apply_icons.py (icon first), so running both leaves no diff
    import subprocess
    subprocess.run([sys.executable, str(fe.REPO / "tools" / "apply_icons.py")], check=True, stdout=subprocess.DEVNULL)
    print(f"wrote {len(I)} items, {len(B) + len(TREE)} blocks, {len(P)} processes, {len(RECIPES) + len(B)} recipes, "
          f"{len(APPEND)} recipe appends, {len(REMOVE_ING) + len(REMOVE_RECIPE)} removals")
    return 0


if __name__ == "__main__":
    sys.exit(main())
