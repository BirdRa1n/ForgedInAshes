"""Print exact copies of vanilla recipes with a different craft_area, ready to paste
inside an <append xpath="/recipes"> block.

Every recipe with that name AND that source craft_area is copied (all variants:
use_smelter / replace_smelter / smelting helpers), effect_groups included.

Usage:
  python tools/copy_recipes.py <from_area> <to_area> <recipeName> [<recipeName> ...]
  python tools/copy_recipes.py forge feFoundry resourceForgedIron resourceNail
"""
import copy
import sys

from lxml import etree

import fe_common as fe


def main() -> int:
    if len(sys.argv) < 4:
        print(__doc__)
        return 2
    src, dst, names = sys.argv[1], sys.argv[2], sys.argv[3:]
    root = fe.load_vanilla("recipes.xml").getroot()
    found = {n: 0 for n in names}
    print(f"<!-- generated by tools/copy_recipes.py {src} -> {dst} from vanilla {fe.game_dir().name} -->")
    for rec in root.iter("recipe"):
        n = rec.get("name")
        if n in found and rec.get("craft_area") == src:
            c = copy.deepcopy(rec)
            c.set("craft_area", dst)
            c.tail = None
            for e in c.iter():
                if e is not c:
                    e.tail = None
            etree.indent(c, space="\t", level=2)
            print("\t\t" + etree.tostring(c, encoding="unicode"))
            found[n] += 1
    missing = [n for n, k in found.items() if not k]
    if missing:
        print(f"<!-- NOT FOUND in craft_area={src}: {', '.join(missing)} -->")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
