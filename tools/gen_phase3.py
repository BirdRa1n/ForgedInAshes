def recipe_xml(name, count, area, time, ingredients, unlocked=True):
    a = f' craft_area="{area}"' if area else ""
    t = f' craft_time="{time}"' if time else ""
    ing = "\n".join(f'\t\t\t<ingredient name="{n}" count="{c}"/>' for n, c in ingredients)
    return f'\t\t<recipe name="{name}" count="{count}"{a}{t} always_unlocked="true">\n{ing}\n\t\t</recipe>'


def region(body: str) -> str:
    return f"\t{BEGIN}\n\t<append xpath=\"/{{root}}\">\n{body}\n\t</append>\n\t{END}"


def write_region(path, root, body):
    s = path.read_text(encoding="utf-8")
    block = region(body).replace("{root}", root)
    if BEGIN in s:
        s = re.sub(re.escape("\t" + BEGIN) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
    else:
        s = s.replace("</configs>", block + "\n</configs>")
    path.write_text(s, encoding="utf-8")


def loc_rows():
    rows = []
    for m in MACHINES:
        _, name, en, pt, den, dpt = m[:6]
        rows.append([name, "blocks", "Block", en, pt])
        rows.append([name + "Desc", "blocks", "Block", den + "\\nRuns only on Charge.", dpt + "\\nFunciona só com Carga."])
    for i in ITEMS:
        _, name, en, pt, den, dpt = i[:6]
        rows.append([name, "items", "Item", en, pt])
        rows.append([name + "Desc", "items", "Item", den, dpt])
    return rows


def write_localization():
    p = fe.MOD_CONFIG / "Localization.csv"
    with p.open(encoding="utf-8", newline="") as fh:
        reader = list(csv.reader(fh))
    header, body = reader[0], reader[1:]
    new = loc_rows()
    keys = {r[0] for r in new}
    body = [r for r in body if r and r[0] not in keys]
    ie, ib = header.index("english"), header.index("brazilian")
    for key, f, typ, en, pt in new:
        row = [""] * len(header)
        row[0], row[1], row[2], row[ie], row[ib] = key, f, typ, en, pt
        body.append(row)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    w.writerows(body)
    p.write_text(buf.getvalue(), encoding="utf-8")


def check():
    icons = fe.game_dir() / "Data" / "ItemIcons"
    vanilla = {e.get("name") for f in ("items.xml", "blocks.xml") for e in fe.load_vanilla(f).getroot()}
    mine = {m[1] for m in MACHINES} | {i[1] for i in ITEMS}
    existing_mod = set()
    for f in ("items.xml", "blocks.xml"):
        t, _ = fe.patched(f)
        existing_mod |= {e.get("name") for e in t.getroot()}
    known = vanilla | mine | existing_mod
    errors = []
    for i in ITEMS:
        if not (icons / f"{i[6]}.png").exists():
            errors.append(f"icon missing: {i[6]} ({i[1]})")
    for m in MACHINES:
        if not (icons / f"{MODELS[m[6]][3]}.png").exists():
            errors.append(f"icon missing: {MODELS[m[6]][3]} ({m[1]})")
        errors += [f"unknown ingredient {n} in {m[1]}" for n, _ in m[9] if n not in known]
    for r in RECIPES:
        if r[0] not in known:
            errors.append(f"unknown recipe output {r[0]}")
        errors += [f"unknown ingredient {n} in {r[0]}" for n, _ in r[4] if n not in known]
    return errors


def main() -> int:
    errors = check()
    for e in errors:
        print("ERROR:", e)
    if errors:
        return 1
    if "--check" in sys.argv:
        print("check OK")
        return 0
    write_region(fe.MOD_CONFIG / "blocks.xml", "blocks", "\n".join(machine_block(m) for m in MACHINES))
    write_region(fe.MOD_CONFIG / "items.xml", "items", "\n".join(item_xml(i) for i in ITEMS))
    rec = [recipe_xml(m[1], 1, None, None, m[9]) for m in MACHINES]
    rec += [recipe_xml(*r) for r in RECIPES]
    write_region(fe.MOD_CONFIG / "recipes.xml", "recipes", "\n".join(rec))
    write_localization()
    print(f"wrote {len(MACHINES)} machines, {len(ITEMS)} items, {len(MACHINES) + len(RECIPES)} recipes, "
          f"{len(loc_rows())} localization rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
