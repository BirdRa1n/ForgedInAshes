"""F3-T03: move vanilla recipes to the mod machines with <set> on craft_area (PLANO_MOD.md section 10.1).

Reads the proposal from tools/remap_proposal.py (recomputed here, not from the CSV, so it is always current)
and writes a GENERATED region in Mods/FerroEngrenagem/Config/recipes.xml with, per enabled machine:
  - <set .../@craft_area> on the recipe(s) with that name in the original vanilla station;
  - for forge recipes: only the non-use_smelter variant moves; its use_smelter twin is <remove>d
    (the game only filters smelter variants when craft_area == "forge", so both would show);
  - forge recipes that already have mod copies in the Foundry (F1-T04) are removed from the forge instead
    of moved (moving them would duplicate the Foundry copies).
Machines that do not exist yet (phase 4: M08, M13, M15) are skipped: those recipes stay vanilla.
The 6 pure smelting recipes of the forge (unit_* -> raw material) are not touched.

Usage:
  python tools/gen_remap.py M01 M02 ...   # machines to include (cumulative: list all enabled batches)
  python tools/gen_remap.py --all          # every phase-3 machine
"""
import collections
import re
import sys

import fe_common as fe
import remap_proposal as rp

BEGIN = "<!-- BEGIN GENERATED by tools/gen_remap.py: do not edit by hand -->"
END = "<!-- END GENERATED by tools/gen_remap.py -->"

# Machines that exist (phase 3 + phase 4 since F4-T01). Name kept for history.
PHASE3 = ["M01", "M02", "M04", "M05", "M06", "M07", "M09", "M10", "M11", "M12", "M14", "M16",
          "M08", "M13", "M15"]
# Forge recipes already copied into the Foundry by hand (F1-T04): remove from forge, do not move.
ALREADY_IN_FOUNDRY = {"resourceForgedIron", "resourceNail", "resourceMetalPipe"}
# The forge's pure smelting helpers (material_based, use_smelter, unit_* only): leave alone.
SMELT_HELPERS = {"resourceClayLump", "resourceCrushedSand", "resourceRockSmall", "resourceScrapBrass",
                 "resourceScrapIron", "resourceScrapLead"}


def plan(enabled):
    root = fe.load_vanilla("recipes.xml").getroot()
    moves = collections.OrderedDict()   # (name, area) -> target craft_area
    removes = []                        # (name, area, only_use_smelter)
    for rec in root.iter("recipe"):
        tags = rec.get("tags") or ""
        if "salvageScrap" in tags:
            continue
        name, area = rec.get("name"), rec.get("craft_area") or "inventory"
        target, _ = rp.classify(area, name, tags)
        if area == "forge" and name in SMELT_HELPERS:
            continue
        if area == "forge" and target == "DROP-VARIANT":
            # decide with the twin: drop only if the twin's recipe is moving/removed in an enabled batch
            twin_target, _ = rp.classify(area, name, "")
            if twin_target in enabled and name not in ALREADY_IN_FOUNDRY:
                removes.append((name, area, True))
            continue
        mid = target.split(":")[-1]
        if target.startswith("REMOVE:"):
            if mid in enabled:
                removes.append((name, area, False))
            continue
        if mid not in enabled or not target.startswith("M"):
            continue
        if area == "forge" and name in ALREADY_IN_FOUNDRY:
            removes.append((name, area, False))
            continue
        moves[(name, area)] = rp.M[mid]
    return moves, removes


def xpath_for(name, area, forge_variant=None):
    if area == "inventory":  # inventory recipes have no craft_area attribute
        return f"/recipes/recipe[@name='{name}'][not(@craft_area) or @craft_area='']"
    base = f"/recipes/recipe[@name='{name}'][@craft_area='{area}']"
    if forge_variant == "replace":
        base += "[not(contains(@tags,'use_smelter'))]"
    elif forge_variant == "use":
        base += "[contains(@tags,'use_smelter')]"
    return base


def render(moves, removes):
    lines = []
    by_target = collections.defaultdict(list)
    for (name, area), ca in moves.items():
        by_target[ca].append((name, area))
    for ca in sorted(by_target):
        lines.append(f"\t<!-- -> {ca} ({len(by_target[ca])}) -->")
        for name, area in by_target[ca]:
            if area == "inventory":  # attribute does not exist yet: setattribute, not set
                lines.append(f'\t<setattribute xpath="{xpath_for(name, area)}" name="craft_area">{ca}</setattribute>')
                continue
            v = "replace" if area == "forge" else None
            lines.append(f'\t<set xpath="{xpath_for(name, area, v)}/@craft_area">{ca}</set>')
    if removes:
        lines.append("\t<!-- forge: use_smelter twins of moved recipes, and recipes already copied to the Foundry -->")
        for name, area, only_use in removes:
            lines.append(f'\t<remove xpath="{xpath_for(name, area, "use" if only_use else None)}"/>')
    return f"\t{BEGIN}\n" + "\n".join(lines) + f"\n\t{END}"


def main() -> int:
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    enabled = PHASE3 if "--all" in sys.argv else args
    bad = [m for m in enabled if m not in PHASE3]
    if bad or not enabled:
        print(__doc__)
        print("unknown/phase-4 machines:", bad)
        return 2
    moves, removes = plan(set(enabled))
    p = fe.MOD_CONFIG / "recipes.xml"
    s = p.read_text(encoding="utf-8")
    block = render(moves, removes)
    if BEGIN in s:
        s = re.sub(re.escape("\t" + BEGIN) + r".*?" + re.escape(END), lambda _: block, s, flags=re.S)
    else:
        s = s.replace("</configs>", block + "\n</configs>")
    p.write_text(s, encoding="utf-8")
    print(f"enabled {enabled}: {len(moves)} <set>, {len(removes)} <remove>")
    return check_tools()


def check_tools() -> int:
    """Every recipe with craft_tool must land in a station whose Workstation/Modules has 'tools'."""
    recipes, _ = fe.patched("recipes.xml")
    blocks, _ = fe.patched("blocks.xml")
    modules = {}
    for bl in blocks.getroot().iter("block"):
        for cls in bl.findall("property"):
            if cls.get("class") == "Workstation":
                m = {x.get("name"): x.get("value") for x in cls.findall("property")}
                for area in (m.get("CraftingAreaRecipes") or "").split(","):
                    modules[area.strip()] = m.get("Modules", "")
    bad = [(r.get("name"), r.get("craft_area"), r.get("craft_tool")) for r in recipes.getroot().iter("recipe")
           if r.get("craft_tool") and (r.get("craft_area") or "").startswith("fe")
           and "tools" not in modules.get(r.get("craft_area"), "")]
    for b in bad:
        print("ERROR: recipe needs a tool but its station has no tool slots:", b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
